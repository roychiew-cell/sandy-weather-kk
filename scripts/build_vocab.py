#!/usr/bin/env python3
"""Rebuild the place-name vocabulary used by the warning-coverage parser and write it into index.html and scripts/fetch.py.

State-scoped: every MetMalaysia forecast location in places.json (towns and districts) is filed under its state, with the
Sabah/Sarawak division tables and a few sub-district names seen in bulletins added to their state. Reviewed aliases map the
different ordinary spellings of one place to one canonical name, and compound names that contain commas or conjunctions are
registered so the parser does not split them. A name that is not in the owning state's vocabulary makes a coverage reading
'undetermined' rather than 'not covered'. Run after places.py:
    python3 scripts/places.py && python3 scripts/build_vocab.py
"""
import json, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
EXTRA = {"sabah": ["Pensiangan", "Paitan", "Labuk & Sugut", "Sook", "Kalabakan"], "sarawak": ["Sebuyau", "Gedong", "Tatau"],
         "pahang": ["Cameron Highlands"], "perak": ["Larut Matang dan Selama"]}
# reviewed aliases: ordinary spellings of one place -> canonical lower-case name
ALIASES = {"tanah tinggi cameron": "cameron highlands", "larut, matang dan selama": "larut matang dan selama",
           "larut, matang and selama": "larut matang dan selama", "larut matang and selama": "larut matang dan selama",
           "labuk sugut": "labuk & sugut", "labuk and sugut": "labuk & sugut"}
# names that contain a separator and must be read as one name
COMPOUNDS = ["larut, matang dan selama", "larut, matang and selama", "larut matang and selama", "larut matang dan selama",
             "labuk & sugut", "labuk and sugut"]
STATE_FIX = {"pulau pinang": "penang", "wp kuala lumpur": "kuala lumpur", "wp putrajaya": "putrajaya", "wp labuan": "labuan"}


def canon(n):
    x = re.sub(r"\s+", " ", n).strip().lower()
    return ALIASES.get(x, x)


def vocab():
    by = {}
    for st, names in EXTRA.items():
        by.setdefault(st, set()).update(canon(x) for x in names)
    for p in json.loads((ROOT / "places.json").read_text(encoding="utf-8"))["places"]:
        if p["kind"] == "state":
            continue
        st = STATE_FIX.get((p.get("state") or "").strip().lower(), (p.get("state") or "").strip().lower())
        if not st:
            continue
        n = p["name"]
        base = re.sub(r"\s*\(.*?\)\s*", "", n).strip()
        s = by.setdefault(st, set())
        for x in {n.strip(), base}:
            if x:
                s.add(canon(x))
        for part in re.split(r"\s+-\s+", base):  # "Tanah Rata - Brinchang": two towns
            if part.strip():
                s.add(canon(part))
    return {k: sorted(v) for k, v in sorted(by.items())}


def main():
    v = vocab()
    lines = {
        "KNOWN_BY_STATE": (json.dumps(v, ensure_ascii=False, separators=(",", ":")), json.dumps(v, ensure_ascii=False)),
        "ALIASES": (json.dumps(ALIASES, ensure_ascii=False, separators=(",", ":")), json.dumps(ALIASES, ensure_ascii=False)),
        "COMPOUNDS": (json.dumps(COMPOUNDS, ensure_ascii=False, separators=(",", ":")), json.dumps(COMPOUNDS, ensure_ascii=False)),
    }
    h = ROOT / "index.html"
    s = h.read_text(encoding="utf-8")
    f = ROOT / "scripts" / "fetch.py"
    t = f.read_text(encoding="utf-8")
    n1 = n2 = 0
    for name, (js, py) in lines.items():
        s, a = re.subn(r"^const %s=.*?// VOCAB[^\n]*$" % name, lambda m: "const %s=%s;   // VOCAB (generated by scripts/build_vocab.py)" % (name, js), s, flags=re.M)
        t, b = re.subn(r"^%s = .*?# VOCAB[^\n]*$" % name, lambda m: "%s = %s  # VOCAB (generated by scripts/build_vocab.py)" % (name, py), t, flags=re.M)
        n1 += a
        n2 += b
    h.write_text(s, encoding="utf-8")
    f.write_text(t, encoding="utf-8")
    print("vocabulary: %s; replaced lines in index.html: %d, fetch.py: %d" % ({k: len(x) for k, x in v.items()}, n1, n2))


if __name__ == "__main__":
    main()
