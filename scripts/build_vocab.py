#!/usr/bin/env python3
"""Rebuild the place-name vocabulary used by the warning-coverage parser and write it into index.html and scripts/fetch.py.

The vocabulary is every MetMalaysia forecast location name in places.json (towns and districts, with bracketed parts and
" - " / "," parts split off) plus the Sabah/Sarawak division tables and a few bulletin-only sub-district names. A name the
parser does not find here makes a coverage reading 'undetermined' rather than 'not covered'. Run after places.py:
    python3 scripts/places.py && python3 scripts/build_vocab.py
"""
import json, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
EXTRA = ["Pensiangan", "Paitan", "Labuk & Sugut", "Sook", "Sebuyau", "Gedong", "Kalabakan", "Tatau"]


def vocab():
    names = set(x.lower() for x in EXTRA)
    for p in json.loads((ROOT / "places.json").read_text(encoding="utf-8"))["places"]:
        if p["kind"] == "state":
            continue
        n = p["name"]
        base = re.sub(r"\s*\(.*?\)\s*", "", n).strip()
        for x in {n.strip(), base}:
            if x:
                names.add(re.sub(r"\s+", " ", x).lower())
        for part in re.split(r"\s+-\s+|,", base):
            if part.strip():
                names.add(part.strip().lower())
    return sorted(names)


def main():
    v = vocab()
    js_line = "const KNOWN_NAMES=" + json.dumps(v, ensure_ascii=False, separators=(",", ":")) + ";   // VOCAB (generated by scripts/build_vocab.py)"
    py_line = "KNOWN_NAMES = " + json.dumps(v, ensure_ascii=False) + "  # VOCAB (generated by scripts/build_vocab.py)"
    h = ROOT / "index.html"
    s = h.read_text(encoding="utf-8")
    s, n1 = re.subn(r"^const KNOWN_NAMES=.*?// VOCAB[^\n]*$", lambda m: js_line, s, flags=re.M)
    h.write_text(s, encoding="utf-8")
    f = ROOT / "scripts" / "fetch.py"
    t = f.read_text(encoding="utf-8")
    t, n2 = re.subn(r"^KNOWN_NAMES = .*?# VOCAB[^\n]*$", lambda m: py_line, t, flags=re.M)
    f.write_text(t, encoding="utf-8")
    print("vocabulary: %d names; replaced in index.html: %d, fetch.py: %d" % (len(v), n1, n2))


if __name__ == "__main__":
    main()
